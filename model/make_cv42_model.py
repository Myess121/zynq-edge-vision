"""Make YOLO-Fastest loadable by OpenCV 4.2 (PYNQ 2.7).

OpenCV 4.2's Darknet importer has no [dropout] layer and reads grouped (depthwise)
convolution weights as if they were dense, which misaligns every later weight.
This writes an equivalent model:
  * [dropout]            -> identity [maxpool] size=1 stride=1 (keeps layer indices)
  * groups=g convolution -> dense convolution with block-diagonal (zero-padded) weights

usage: python make_cv42_model.py in.cfg in.weights out.cfg out.weights
"""
import sys
import numpy as np


def parse_cfg(path):
    blocks = []
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        if line.startswith("["):
            blocks.append({"type": line[1:-1]})
        else:
            k, v = line.split("=", 1)
            blocks[-1][k.strip()] = v.strip()
    return blocks


def write_cfg(blocks, path):
    with open(path, "w") as f:
        f.write("# generated by make_cv42_model.py for OpenCV < 4.5\n")
        for b in blocks:
            f.write("[%s]\n" % b["type"])
            for k, v in b.items():
                if k != "type":
                    f.write("%s=%s\n" % (k, v))
            f.write("\n")


def main(cfg_in, w_in, cfg_out, w_out):
    blocks = parse_cfg(cfg_in)
    net, layers = blocks[0], blocks[1:]
    raw = open(w_in, "rb").read()
    major, minor, rev = np.frombuffer(raw, np.int32, 3)
    hdr = 20 if major * 10 + minor >= 2 else 16
    header, data = raw[:hdr], np.frombuffer(raw[hdr:], np.float32)
    pos, out = 0, []

    ch = [int(net.get("channels", 3))]  # ch[i+1] = output channels of layer i
    for i, b in enumerate(layers):
        t = b["type"]
        cin = ch[-1]
        if t == "convolutional":
            n, k = int(b["filters"]), int(b["size"])
            g = int(b.get("groups", 1))
            nb = 4 * n if int(b.get("batch_normalize", 0)) else n
            out.append(data[pos:pos + nb]); pos += nb
            nw = n * (cin // g) * k * k
            w = data[pos:pos + nw].reshape(n, cin // g, k, k); pos += nw
            if g > 1:
                dense = np.zeros((n, cin, k, k), np.float32)
                og, ig = n // g, cin // g
                for j in range(g):
                    dense[j * og:(j + 1) * og, j * ig:(j + 1) * ig] = w[j * og:(j + 1) * og]
                w = dense
                del b["groups"]
            out.append(w.ravel())
            ch.append(n)
        elif t == "dropout":
            b.clear(); b.update({"type": "maxpool", "size": "1", "stride": "1"})
            ch.append(cin)
        elif t == "route":
            idx = [int(x) for x in b["layers"].split(",")]
            ch.append(sum(ch[(x if x >= 0 else i + x) + 1] for x in idx))
        else:  # maxpool, shortcut, upsample, yolo keep the channel count
            ch.append(cin)
    assert pos == data.size, "weights left over: %d of %d" % (data.size - pos, data.size)
    write_cfg([net] + layers, cfg_out)
    with open(w_out, "wb") as f:
        f.write(header)
        f.write(np.concatenate(out).astype(np.float32).tobytes())
    print("ok: %d layers, %d -> %d floats" % (len(layers), data.size, sum(a.size for a in out)))


if __name__ == "__main__":
    main(*sys.argv[1:5])
